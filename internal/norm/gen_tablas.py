"""Genera tablas.go con los datos Unicode que necesita el port del jurado.

    python3 internal/norm/gen_tablas.py | gofmt > internal/norm/tablas.go

El jurado (docs/validar.mjs) normaliza con NFKC y NFD, que en Node vienen de ICU.
Go no trae normalización Unicode en la biblioteca estándar y el proyecto no
admite dependencias nuevas, así que las tablas se generan aquí, desde
unicodedata, y el paquete las aplica con el algoritmo de UAX#15.

Qué se emite:
- canónicas y compatibilidades: descomposición de un paso (la recursión la hace
  Go). Hangul queda fuera porque su descomposición es algorítmica.
- compuestos: pares (base, marca) que NFC vuelve a componer. Se derivan
  preguntándole a unicodedata, así que las exclusiones de composición ya están
  aplicadas.
- clases: clase de combinación canónica distinta de cero, para reordenar.
"""

import sys
import unicodedata

HASTA = 0x110000
BASE_HANGUL = 0xAC00
FIN_HANGUL = 0xD7A4


def descomposicion(ch):
    """(es_compatibilidad, runas) de la descomposición de un paso."""
    texto = unicodedata.decomposition(ch)
    if not texto:
        return None
    partes = texto.split()
    compat = partes[0].startswith("<")
    if compat:
        partes = partes[1:]
    return compat, [int(p, 16) for p in partes]


def escribe(salida, nombre, tipo, lineas):
    salida.write(f"var {nombre} = {tipo}{{\n")
    for linea in lineas:
        salida.write(f"\t{linea},\n")
    salida.write("}\n\n")


def main():
    salida = sys.stdout
    salida.write(
        "// Code generated by gen_tablas.py; DO NOT EDIT.\n"
        "//\n"
        f"// Fuente: unicodedata {unicodedata.unidata_version}. Regenerar con\n"
        "//\n"
        "//\tpython3 internal/norm/gen_tablas.py | gofmt > internal/norm/tablas.go\n"
        "package norm\n\n"
    )

    canonicas = []
    compatibilidades = []
    for cp in range(HASTA):
        if BASE_HANGUL <= cp < FIN_HANGUL:
            continue
        dato = descomposicion(chr(cp))
        if dato is None:
            continue
        compat, runas = dato
        if compat:
            compatibilidades.append((cp, runas))
        else:
            canonicas.append((cp, runas))

    compuestos = []
    for cp, runas in canonicas:
        if len(runas) != 2:
            continue
        base, marca = runas
        if unicodedata.normalize("NFC", chr(base) + chr(marca)) == chr(cp):
            compuestos.append(((base, marca), cp))

    clases = [
        (cp, unicodedata.combining(chr(cp)))
        for cp in range(HASTA)
        if unicodedata.combining(chr(cp))
    ]

    def runas_go(runas):
        # \u lleva cuatro dígitos y \U ocho: sin esto, una runa astral se
        # parte en dos y la tabla queda corrupta en silencio.
        escapes = [f"\\u{r:04x}" if r <= 0xFFFF else f"\\U{r:08x}" for r in runas]
        return '"' + "".join(escapes) + '"'

    escribe(
        salida,
        "canonicas",
        "map[rune]string",
        (f"0x{cp:04x}: {runas_go(runas)}" for cp, runas in canonicas),
    )
    escribe(
        salida,
        "compatibilidades",
        "map[rune]string",
        (f"0x{cp:04x}: {runas_go(runas)}" for cp, runas in compatibilidades),
    )
    escribe(
        salida,
        "compuestos",
        "map[[2]rune]rune",
        (f"{{0x{par[0]:04x}, 0x{par[1]:04x}}}: 0x{cp:04x}" for par, cp in compuestos),
    )
    escribe(
        salida,
        "clases",
        "map[rune]uint8",
        (f"0x{cp:04x}: {clase}" for cp, clase in clases),
    )


if __name__ == "__main__":
    main()
